def render(template: str, a: str, b: str, reason: str = "") -> str:
    from html import escape
    text = escape(template).replace("{a}", a).replace("{b}", b)
    if reason:
        text += f"\n💬 Со словами: «{escape(reason[:200])}»"
    return text
